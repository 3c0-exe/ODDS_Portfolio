        <span class="about-origin-label">Before the name</span>
        <h3>We knew each other.<br>And each other’s habits.</h3>
        <p>At SPCC-CIT’s multimedia group, Jerico Sanchez directed the team, Robert Santiago Jr. was his assistant director, Brix Cura led editing and design, and Jherald Vibar led development. Several of the people you’ll meet below were there with us, too.</p>
        <p>We handled projects, worked with clients, and learned each other’s habits. Years of working together gave us a kind of trust that would’ve been difficult to build from scratch.</p>
