        <span class="about-origin-label">August 2025</span>
        <h3>Something of our own.</h3>
        <p>When our term ended, we didn’t have a concrete plan for what came next. Then Jerico brought in a few clients, and continuing together started to feel real. We could bring everything we’d been practicing—multimedia, design, and development—into work of our own.</p>
        <p class="about-origin-milestone">By August 2025, we were calling it ODDS.</p>
        </div>
    </div>
    <div class="about-story-belief">
        <span class="about-origin-label">The name stuck for a reason.</span>
        <h3>Against All ODDS.</h3>
        <p>Jerico chose the name from “Against All ODDS.” It fit something we already believed: put the effort into the work, especially when it gets difficult. And if we can’t give a project our full attention, we have to be honest about that, too.</p>
    </div>
